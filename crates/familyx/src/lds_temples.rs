/// The place text for an old LDS fact: the temple name for a known code or alias, the first temple whose name
/// starts with a longer text, and the text itself otherwise.
pub(crate) fn temple_name(code: &str) -> String {
    if code.trim().is_empty() {
        return code.to_string();
    }
    let upper = code.to_uppercase();
    let normalized = ALIASES.iter().find(|(a, _)| *a == upper).map_or(code, |(_, c)| *c);
    if let Some((_, name)) = TEMPLES.iter().find(|(c, _)| *c == normalized) {
        return (*name).to_string();
    }
    if code.chars().count() > 5 {
        let lower = code.to_lowercase();
        if let Some((_, name)) = TEMPLES.iter().find(|(_, n)| n.to_lowercase().starts_with(&lower)) {
            return (*name).to_string();
        }
    }
    code.to_string()
}

#[cfg(test)]
mod tests {
    use super::temple_name;

    #[test]
    fn codes_aliases_and_names() {
        assert_eq!(temple_name("SLAKE"), "Salt Lake Temple");
        assert_eq!(temple_name("SL"), "Salt Lake Temple");
        assert_eq!(temple_name("slake"), "slake", "codes are case sensitive, aliases are not");
        assert_eq!(temple_name("LONDO"), "London England Temple");
        assert_eq!(temple_name("XYZZY"), "XYZZY");
        assert_eq!(temple_name("Salt Lake T"), "Salt Lake Temple", "longer text matches the start of a name");
        assert_eq!(temple_name(" "), " ");
    }
}
